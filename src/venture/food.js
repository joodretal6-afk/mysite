// ── تخمين الفئة من اسم الصنف ──
const HINTS = [
  [/لبنة|جبن|أجبان|لبن|حليب|قشطة|زبدة|شنينة|كشك/, "dairy_fresh"],
  [/غنم|لحم|دجاج|سمك|خروف|عجل|كباب|برغر|مجمد/, "meat_frozen"],
  [/كيك|حلو|معجن|خبز|بسكوت|كنافة|بقلاو|شوكولا/, "bakery"],
  [/وجبة|وجبات|سلطة|شوربة|طبخ|مطبخ/, "prepared"],
  [/عصير|مشروب|شاي|قهوة سائل|ماء|كمبوت/, "beverages"],
  [/فيتامين|مكمل|بروتين|كولاجين|عشب|دواء|علاج|تخسيس/, "supplements"],
  [/بهار|مكسرات|عسل|زيت|تمر|أرز|رز|حبوب|طحين|سكر|قهوة|زعتر|سماق/, "dry_shelf"]
];

export function guessCategory(productName) {
  const p = String(productName || "");
  for (const [re, key] of HINTS) if (re.test(p)) return { key, ...CATEGORIES[key], guessed: true };
  return { key: "dry_shelf", ...CATEGORIES.dry_shelf, guessed: false,
           note: "ما قدرنا نحدد الفئة من الاسم — افترضنا جاف. صحّحها يدوياً لأنها بتغيّر كل الحسابات." };
}

