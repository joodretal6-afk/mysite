export function adLibraryLinks(product, country = "JO") {
  const c = String(country || "JO").toUpperCase().slice(0, 2);
  const base = "https://www.facebook.com/ads/library/?active_status=active&ad_type=all&media_type=all";
  const mk = (q, label, why) => ({
    label, why,
    url: `${base}&country=${encodeURIComponent(c)}&q=${encodeURIComponent(q)}&search_type=keyword_unordered`
  });
  const p = String(product || "").trim();
  return [
    mk(p, `كل إعلانات "${p}" النشطة`, "مين بيعلن على نفس صنفك هلأ — أهم شاشة تفتحها"),
    mk(`${p} توصيل`, `"${p}" + توصيل`, "اللي بيبيعوا أونلاين تحديداً مش المحلات"),
    mk(`${p} عرض`, `"${p}" + عرض`, "شو العروض الشغّالة بالسوق — بتعرف منها سقف الخصومات"),
    mk(`${p} طبيعي`, `"${p}" + طبيعي`, "زاوية المنتج الطبيعي/البلدي — شائعة بالأغذية"),
    mk(`${p} اصلي`, `"${p}" + أصلي`, "زاوية الأصالة — بتكشف إذا السوق فيه مشكلة تقليد")
  ];
}

