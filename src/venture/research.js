const MAX_STEPS = 6;

// ═══════════════════════════════════════════════════════════
// 🔗 روابط مكتبة إعلانات ميتا — دقيقة وجاهزة للضغط
// هاي أقوى أداة مجانية لرؤية إعلانات منافسيك، وأغلب التجار
// ما بيعرفوا إنها موجودة أصلاً.
