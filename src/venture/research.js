// 🤖 حلقة الوكيل الباحث — بحث حقيقي ثم تحليل
// نفس نمط askMarket الموجود، بس مخصّص للأغذية والمنافسة.
// ═══════════════════════════════════════════════════════════
// يمرّ من الطبقة الموحّدة — فيشتغل بأي مزوّد مربوط (AIsa أو Gemini)
async function callAI(sys, userText) {
  const { aiComplete } = await import("../bot/aiCore.js");
  const r = await aiComplete(`${sys}\n\n---\n\n${String(userText).slice(0, 12000)}`,
    { temperature: 0.4, maxTokens: 2600, timeoutMs: 60000 });
  if (!r.ok) throw new Error(r.error || "فشل الذكاء الاصطناعي");
  return String(r.text || "").replace(/\*\*/g, "").trim();
}

const RESEARCHER = `أنت باحث سوق متخصص بالمنتجات الغذائية للبيع عبر فيسبوك بالدفع عند الاستلام.

قواعد صارمة:
- ممنوع تأليف أرقام. أي سعر أو معلومة لازم تكون من نتيجة بحث فعلية أعطيتك إياها.
- إذا ما لقيت معلومة، اكتب صراحة "ما لقيت بيانات عن هذا" ولا تخمّن.
- ميّز دائماً بين "من مصدر" و"تقدير خبرة".
- لا تدّعي أنك رأيت صفحات فيسبوك إذا لم تُعطَ محتواها.
- انتبه: هذه منتجات غذائية — الصلاحية والتبريد والتراخيص عوامل حاسمة.
- اللهجة: أردنية مهنية مختصرة. لا مبالغة تسويقية.

للبحث اكتب سطراً منفصلاً واحداً ثم توقف: [[SEARCH:عبارة البحث]]
لفتح صفحة: [[FETCH:الرابط]]
بعد 3-5 عمليات بحث اكتب التحليل النهائي مع ذكر الروابط المصدر.`;

export async function research(topic, onStep) {
  const steps = [];
  let convo = `المطلوب: ${topic}`;

  for (let i = 0; i < MAX_STEPS; i++) {
    let text;
    try { text = await callAI(RESEARCHER, convo); }
    catch (e) { return { ok: false, error: e.message, steps }; }

    const s = text.match(/\[\[SEARCH:([\s\S]*?)\]\]/);
    const f = text.match(/\[\[FETCH:([\s\S]*?)\]\]/);
    if (!s && !f) return { ok: true, report: text, steps };

    let result = "";
    try {
      if (s) {
        const q = s[1].trim().slice(0, 200);
        steps.push({ type: "search", q });
        if (onStep) onStep({ type: "search", q });
        const res = await webSearch(q, 8);
        result = res.length
          ? `[نتائج حقيقية عن: ${q}]\n` + res.map((r, j) =>
              `${j + 1}. ${r.title}\n   ${r.url}\n   ${r.snippet}`).join("\n")
          : `[لا نتائج عن: ${q}]`;
      } else {
        const url = f[1].trim().slice(0, 500);
        steps.push({ type: "fetch", q: url });
        if (onStep) onStep({ type: "fetch", q: url });
        const p = await fetchPage(url);
        result = p.status >= 400 || !p.text
          ? `[تعذّر فتح ${url} — HTTP ${p.status}]`
          : `[محتوى ${p.title || url}]\n${p.text}`;
      }
    } catch (e) { result = `[فشل التنفيذ: ${e.message}]`; }

    convo += `\n\n${text}\n\n${result}`;
  }
  return { ok: true, report: "وصلنا الحد الأقصى للبحث بلا خلاصة نهائية.", steps, truncated: true };
}

