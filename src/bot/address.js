// مرادفات شائعة تنطبع لصيغة موحّدة قبل المطابقة.
// ⚠️ ممنوع استخدام \b هون: بالجافاسكربت \b مبنية على محارف ASCII،
//    فما بتشتغل مع العربي إطلاقاً. منستخدم حدود صريحة بدلها.
const BD = "(?:^|[\\s،,.:/\\-])";
const AD = "(?=$|[\\s،,.:/\\-])";
// البادئة الملتصقة لازم تنقبل هون كمان: "بالسابع" = بال + سابع
const PFX = "(?:بال|وال|فال|لل|ولل|ال|ب|و|ف|ل|ك)?";
const alias = (from, to) => [new RegExp(BD + PFX + from + AD, "g"), " " + to];

// 🔴 الأعداد الترتيبية سلاح ذو حدين: "الثالث" ممكن تكون دوار وممكن تكون طابق.
//    بلا هالحارس، "طابق الثالث" بتنقلب "طابق الدوار الثالث" وبتكسر مطابقة المنطقة.
//    فمنستثني الترتيبي إذا كان مسبوقاً بكلمة بتخليه وصف داخلي مش موقع.
const ORDINAL_BLOCK = /(?:طابق|الطابق|طبقه|شقه|شقة|رقم|بنايه|عماره|دخله|حاره|مره)\s*$/;
const ordAlias = (from, to) => ({ ord: true, re: new RegExp(BD + PFX + from + AD, "g"), to: " " + to });

const ALIASES = [
  alias("الزرقا", "الزرقاء"), alias("البترا", "البتراء"),
  alias("داخليه", "دوار الداخليه"), alias("جامعه الاردنيه", "الجبيهه")
];
const ORD_ALIASES = [
  ordAlias("سابع", "الدوار السابع"), ordAlias("ثامن", "الدوار الثامن"),
  ordAlias("خامس", "الدوار الخامس"), ordAlias("سادس", "الدوار السادس"),
  ordAlias("رابع", "الدوار الرابع"), ordAlias("ثالث", "الدوار الثالث")
];

// تطبيق الترتيبيات مع احترام الحارس
function applyOrdinals(t) {
  for (const a of ORD_ALIASES) {
    t = t.replace(a.re, (m, ...rest) => {
      const off = rest[rest.length - 2];
      return ORDINAL_BLOCK.test(t.slice(Math.max(0, off - 14), off + 1)) ? m : a.to;
    });
  }
  return t;
}

// البادئات العربية الملتصقة: "بالجبيهة" = بـ + الجبيهة.
// هاي كانت أكبر سبب فشل مطابقة — الكلمة موجودة بس ملتصقة ببادئة.
const PREFIX = "(?:ب|و|ف|ل|ك|بال|وال|فال|لل|ولل)?";

function keyRegex(key) {
  const esc = key.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  // البادئة ممكن تجي قبل الـ"ال" أو بدلها
  const withoutAl = esc.startsWith("ال") ? esc.slice(2) : null;
  const alt = withoutAl ? `(?:${esc}|${PREFIX}ال${withoutAl})` : `${PREFIX}${esc}`;
  return new RegExp(BD + alt + AD);
}
const KEY_RE = new Map(GAZ_KEYS.map(k => [k, keyRegex(k)]));

// كلمات النفي — عشان "انا بالجبيهة مش صويلح" ما تنقرأ صويلح
const NEG = /(?:مش|مو|ليس|لا|بدون|غير)\s*$/;

// ═══════════════════════════════════════════════════════════
// 🔎 مطابقة المنطقة
// بترجّع أفضل ترشيح غير منفي. المنفي بينحفظ عشان نعرف
// إن الزبون استثناه صراحةً — وهاد بيفرق كثير بالتصحيح.
// ═══════════════════════════════════════════════════════════
export function matchArea(normText) {
  let t = " " + normText + " ";
  for (const [re, rep] of ALIASES) t = t.replace(re, rep);
  t = applyOrdinals(t);

  const hits = [];
  // 1) مطابقة مباشرة — الأطول أولاً ("ماركا الشماليه" قبل "ماركا")
  for (const key of GAZ_KEYS) {
    const m = t.match(KEY_RE.get(key));
    if (!m) continue;
    const at = m.index + m[0].indexOf(key.slice(-3));
    const before = t.slice(Math.max(0, at - 12), at);
    hits.push({ area: key, governorate: GAZETTEER[key], match: "مباشرة",
                typo: false, at, negated: NEG.test(before) });
  }
  if (hits.length) {
    // نفضّل غير المنفي، وبعدين الأطول (أدق)
    const live = hits.filter(h => !h.negated);
    const pick = (live.length ? live : hits)
      .sort((a, b) => b.area.length - a.area.length)[0];
    return { ...pick, negatedOthers: hits.filter(h => h.negated).map(h => h.area) };
  }

  // 2) المحافظة لحالها
  for (const g of GOVERNORATES) {
    const gn = normalizeAr(g);
    if (keyRegex(gn).test(t))
      return { area: null, governorate: g, match: "محافظة فقط", typo: false };
  }

  // 3) مطابقة تقريبية — للأخطاء الإملائية. منشيل البادئات قبل المقارنة.
  const strip = w => w.replace(/^(?:بال|وال|فال|لل|ولل|ب|و|ف|ل|ك)(?=ال)/, "")
                      .replace(/^(?:ب|و|ف|ل|ك)(?=[^ا])/, "");
  const words = normText.split(/[\s،,.]+/).map(strip).filter(w => w.length >= 4);
  for (const w of words) {
    for (const key of GAZ_KEYS) {
      if (Math.abs(key.length - w.length) > 2) continue;
      const max = key.length <= 5 ? 1 : 2;
      if (editDistance(w, key, max) <= max)
        return { area: key, governorate: GAZETTEER[key], match: "تقريبية", typo: true, wrote: w };
    }
  }
  // 4) كلمتين متجاورتين (لأسماء المناطق المركّبة)
  const ws = normText.split(/[\s،,.]+/).map(strip).filter(Boolean);
  for (let i = 0; i < ws.length - 1; i++) {
    const pair = ws[i] + " " + ws[i + 1];
    for (const key of GAZ_KEYS) {
      if (!key.includes(" ")) continue;
      if (editDistance(pair, key, 2) <= 2)
        return { area: key, governorate: GAZETTEER[key], match: "تقريبية", typo: true, wrote: pair };
    }
  }
  return null;
}

