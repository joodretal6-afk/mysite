// ── تطبيع عربي: الألف والهاء والتاء المربوطة والتشكيل والتطويل ──
export function normalizeAr(s) {
  return String(s || "")
    .replace(/[ً-ٰٟ]/g, "")          // تشكيل
    .replace(/ـ/g, "")                          // تطويل ـــ
    .replace(/[إأآٱا]/g, "ا")
    .replace(/[ىي]/g, "ي")
    .replace(/[ؤئء]/g, "ء")
    .replace(/ة/g, "ه")                              // الجبيهة = الجبيهه
    .replace(/[٠-٩]/g, d => String("٠١٢٣٤٥٦٧٨٩".indexOf(d)))
    .replace(/[۰-۹]/g, d => String("۰۱۲۳۴۵۶۷۸۹".indexOf(d)))
    .replace(/\s+/g, " ")
    .trim();
}

// ── مسافة تحرير محدودة — للأخطاء الإملائية ──
function editDistance(a, b, max = 2) {
  if (Math.abs(a.length - b.length) > max) return max + 1;
  const prev = Array(b.length + 1).fill(0).map((_, i) => i);
  for (let i = 1; i <= a.length; i++) {
    let cur = [i], best = i;
    for (let j = 1; j <= b.length; j++) {
      const v = a[i - 1] === b[j - 1] ? prev[j - 1]
        : 1 + Math.min(prev[j - 1], prev[j], cur[j - 1]);
      cur[j] = v; if (v < best) best = v;
    }
    if (best > max) return max + 1;
    for (let j = 0; j <= b.length; j++) prev[j] = cur[j];
  }
  return prev[b.length];
}

