export function extractPhone(memory, text, sourceMid = null) {
  // نوحّد الصيغة الدولية ثم نبحث عن رقم أردني صحيح
  const norm = text.replace(/[\s\-\.]/g, "").replace(/(?:\+962|00962)7/g, "07");
  const valid = norm.match(/07[789]\d{7}/);
  if (valid) {
    memory.phone = valid[0]; memory.invalidPhoneProvided = false;
    // 🧾 الرقم مصدره هالرسالة بالضبط — إثبات إنه من العميل نفسه.
    recordSource(memory, "phone", valid[0], sourceMid);
    return;
  }

  // نعتبره "رقم خاطئ" فقط إذا بدا كمحاولة رقم هاتف (يبدأ بـ 07/+962) لكن غير مكتمل،
  // حتى لا نظنّ أرقام العناوين (عمارة 123، رقم بناية...) رقم هاتف خاطئ.
  const looksLikePhoneAttempt = /(?:^|[^0-9])(?:07\d{4,}|(?:\+962|00962)\d{6,})/.test(text.replace(/[\s\-\.]/g, ""));
  memory.invalidPhoneProvided = (!memory.phone && looksLikePhoneAttempt) ? true : false;
}

export function extractQty(text, pageConfig) {
  // ⚠️ الوزن ليس كمية: النصية الواحدة وزنها 4 كيلو. لازم نميّز الكمية عن الكيلوهات والأسعار والعناوين.
  // 1) نحسب الكيلوهات من النص الأصلي (قبل أي حذف) لأن الوزن قد يدل على العدد
  if (pageConfig.QTY_MODE === "kilo") {
    const kg = text.match(/(\d+(?:\.\d+)?)\s*(?:كيلو|كغ|كجم|كيلوغرام)/);
    if (kg) return parseFloat(kg[1]);
  }

  // 2) ننظّف: نشيل أرقام العناوين + الأوزان + الأسعار حتى لا تُحسب كمية
  const clean = text
    .replace(/(عمارة|بناية|شارع|طابق|رقم|شقة|دوار|حي)\s*\d+/gi, " ")
    .replace(/\d+(?:\.\d+)?\s*(?:كيلو|كغ|كجم|كيلوغرام|غرام|جرام|غم|جم|كباو|كباية|علبة|علب)/gi, " وزن ")
    .replace(/\d+(?:\.\d+)?\s*(?:دينار|دنانير|jd)/gi, " ")
    .replace(/\b\d{3,}\b/g, " ");   // أرقام طويلة (هواتف/أوزان بالغرام مثل 4200)

  // كمية من ذكر الكيلوهات صراحةً (النصية = 4 كيلو) — من النص الأصلي
  if (/(16\s*كيلو|ستة عشر كيلو)/.test(text)) return 4;
  if (/(12\s*كيلو|اثنا عشر كيلو|اثنعش كيلو)/.test(text)) return 3;
  if (/(8\s*كيلو|ثمانية كيلو|ثماني كيلو|ثمن كيلو)/.test(text)) return 2;
  if (/(4\s*كيلو|اربعة كيلو|أربعة كيلو|اربع كيلو|أربع كيلو)/.test(text)) return 1;

  // 3) كلمات الكمية الصريحة (تثنية/جمع/مفرد)
  if (/(نصيتين|نصيّتين|ثنتين|تنتين|اثنتين|عبوتين|قصتين|سطليتين|ربعيتين|حبتين|علبتين|كباويتين)/.test(clean)) return 2;
  if (/(ثلاث|تلات|تلت)\s*(?:نصيات|نصايا|عبوات|حبات|قصص|قطع|علب|كباوي)?/.test(clean)) return 3;
  if (/(اربع|أربع|أربعة|اربعة)\s*(?:نصيات|نصايا|عبوات|حبات|قصص|قطع|علب|كباوي)/.test(clean)) return 4;
  if (/(خمس|خمسة)\s*(?:نصيات|نصايا|عبوات|حبات|قصص|قطع|علب|كباوي)/.test(clean)) return 5;

  // مفرد = 1 (أضفنا "حبة" و "كباية/كباوة")
  if (/(نصية|نصيه|نصّية|وحدة|وحده|واحدة|واحده|عبوة|عبوه|قصة|قصه|سطلية|ربعية|حبة|حبه|حباية|كباية|كباوة|كباوه)/.test(clean)) return 1;

  // 4) رقم متبوع بوحدة عدّ صريحة فقط (مش وزن ولا سعر ولا عنوان)
  const m = clean.match(/(?:^|\s|بدي|عدد|كمية|كميه)\s*([1-9])\s*(نصي|نصاي|عبو|حب|قص|قطع|سطلي|ربعي|علب|كباو|وحد)/);
  if (m) return parseInt(m[1], 10);

  return 0;   // غير واضح → لا نخمّن (الأفضل نسأل الزبون بدل ما نضاعف طلبه)
}

// ═══════════════════════════════════════════════════════════
// 📍 استخراج العنوان — عبر محرّك العناوين (bot/address.js)
//
// اللي تغيّر جذرياً عن النسخة القديمة:
//  • بيتراكم ويتصحّح بدل ما يتقفل على أول التقاطة
//  • بيخزّن العنوان منسّقاً، مش الرسالة كاملة
//  • معه درجة ثقة وقائمة نواقص وسؤال واحد محدّد
//  • السؤال ما بينحسب عنوان حتى لو سألنا عن العنوان قبله
// ═══════════════════════════════════════════════════════════
export function extractArea(memory, text, sourceMid = null) {
  // منشيل رقم الهاتف بس — مش كل رقم. أرقام البنايات والشقق لازم تضل.
  const stripped = text.replace(/(?:\+962|00962)?0?7[789]\d{7}/g, " ").trim();
  if (stripped.length < 2) return;

  const wasAsked = !!(memory.lastReply &&
    /(عنوان|موقع|محافظ|وين|منطقت|مكانك|سكنك|أقرب معلم|اقرب معلم)/.test(memory.lastReply));

  const correcting = isCorrection(stripped);
  // إذا مش محاولة عنوان ولا تصحيح — منتجاهله بهدوء
  if (!correcting && !looksLikeAddressAttempt(stripped, { wasAsked })) return;

  const before = memory.addr || null;
  // المطابقة التقريبية بتشتغل بس لما نكون واثقين إنه النص عنوان:
  // البوت سأل صراحةً، أو الزبون بيصحّح. غير هيك، ممنوع نخترع منطقة
  // من كلمة منتج زي "الغسيل" (اللي كانت بتطابق "الضليل").
  const next = mergeAddress(before, stripped, { force: correcting, fuzzy: wasAsked || correcting });

  // ما منستبدل عنوان أقوى بأضعف إلا لو الزبون بيصحّح صراحةً
  if (before && !correcting && next.score < before.score) return;

  memory.addr = next;
  memory.area = next.formatted;                 // اللي بيروح للفاتورة
  memory.addressScore = next.score;
  memory.addressLevel = next.level;
  memory.addressReady = next.deliverable;
  memory.addressMissing = next.missing;
  memory.addressQuestion = next.nextQuestion;   // سؤال واحد محدّد
  // 🧾 العنوان مصدره كلام العميل بهالرسالة (بعد ما عدّى محرّك العنوان
  //    اللي أصلاً بيرفض أي كلمة مش من نص العميل).
  recordSource(memory, "area", next.formatted, sourceMid);
}

export function parseMessage(memory, originalText, pageConfig, sourceMid = null) {
  const text = normalizeDigits(originalText);

  if (!memory.cart) memory.cart = {};

  const cartBefore = JSON.stringify(memory.cart);

  extractPhone(memory, text, sourceMid);

  const qty = extractQty(text, pageConfig);

  // ═══════════════════════════════════════════════════════════
  // 🔴 ربط كل كمية بصنفها — مسح بالمواقع لا فحص عام
  //
  // النسخة السابقة كانت تحسب كمية واحدة للرسالة كلها وتطبّقها على كل
  // صنف انذكر فيها. فـ«نصية غنم ونصيتين شخل» كانت تطلع {غنم:2, شخل:2}،
  // يعني الزبون بينحاسب على 4 نصيات بدل 3 — خطأ مباشر بالفاتورة والفلوس.
  //
  // الحل: منلاقي موقع كل صنف بالنص، ومنقرأ الكمية من المقطع اللي قبله.
  // بالعربي الكمية بتسبق الصنف غالباً («نصية غنم»)، فالمقطع اللي قبل
  // الصنف هو المكان الصح للبحث عنها.
  // ═══════════════════════════════════════════════════════════
  const keywords = pageConfig.PRODUCT_KEYWORDS || {};
  const hits = [];
  for (const [product, regex] of Object.entries(keywords)) {
    // ننسخ التعبير بعلم g عشان نلاقي كل المواقع بلا ما نعبث بالأصلي
    const rx = new RegExp(regex.source, regex.flags.includes("g") ? regex.flags : regex.flags + "g");
    let m;
    while ((m = rx.exec(text)) !== null) {
      hits.push({ product, at: m.index, end: m.index + m[0].length });
      if (m.index === rx.lastIndex) rx.lastIndex++;   // حماية من حلقة لا نهائية
    }
  }
  hits.sort((a, b) => a.at - b.at);

  let productFound = hits.length > 0;
  if (hits.length === 1) {
    // صنف واحد: نستخدم كمية الرسالة كاملة — أدق لأن الكمية ممكن تجي بعده
    const h = hits[0];
    memory.cart[h.product] = qty > 0 ? qty : (memory.cart[h.product] || 1);
  } else if (hits.length > 1) {
    let prevEnd = 0;
    const seen = new Set();
    for (const h of hits) {
      if (seen.has(h.product)) { prevEnd = h.end; continue; }   // أول ذكر بس
      seen.add(h.product);
      const segment = text.slice(prevEnd, h.at);       // المقطع اللي قبل الصنف
      const segQty = extractQty(segment, pageConfig);
      memory.cart[h.product] = segQty > 0 ? segQty : (memory.cart[h.product] || 1);
      prevEnd = h.end;
    }
  }

  // ذكر كمية بدون صنف والسلة فيها صنف واحد → حدّث كميته
  if (qty > 0 && !productFound) {
    const keys = Object.keys(memory.cart);
    if (keys.length === 1) memory.cart[keys[0]] = qty;
  }

  // 🧾 لو السلة تغيّرت بهالرسالة، مصدر الطلب هو هالرسالة.
  if (JSON.stringify(memory.cart) !== cartBefore && Object.keys(memory.cart).length)
    recordSource(memory, "order", { ...memory.cart }, sourceMid);

  extractArea(memory, text, sourceMid);
  return memory;
}
