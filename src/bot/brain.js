export function findProductMatches(pageId, text = "") {
  const page = getPage(pageId);
  if (!page) return [];
  const hits = [];
  for (const [product, matcher] of Object.entries(page.PRODUCT_KEYWORDS || {})) {
    try {
      matcher.lastIndex = 0;
      if (matcher.test(String(text))) hits.push(product);
      matcher.lastIndex = 0;
    } catch {
      // safe fallback
    }
  }
  return [...new Set(hits)];
}

export function calculateOrderTotal(pageId, lines = [], deliveryMode = "auto") {
  const page = getPage(pageId);
  if (!page) return null;

  const quantities = new Map();
  for (const line of Array.isArray(lines) ? lines : []) {
    const product = String(line?.product || "").trim();
    const quantity = Number(line?.quantity || 1);
    if (!product || !Number.isFinite(quantity) || quantity <= 0) continue;
    quantities.set(product, (quantities.get(product) || 0) + quantity);
  }

  let subtotal = 0;
  let appliedOffers = [];
  let deliveryIncluded = false;
  let hasChargeableItems = false;
  let hasPricedItems = false;
  let allPricedItemsInclusive = true;

  if (Array.isArray(page.BUNDLE_OFFERS)) {
    for (const bundle of page.BUNDLE_OFFERS) {
      if (!Array.isArray(bundle.products) || !Number.isFinite(Number(bundle.price))) continue;
      const needed = bundle.products.map(bp => ({
        name: bp.name,
        quantity: Math.max(1, Number(bp.quantity || 1))
      }));

      let canApply = true;
      while (canApply) {
        canApply = needed.every(bp => (quantities.get(bp.name) || 0) >= bp.quantity);
        if (!canApply) break;

        for (const bp of needed) {
          const left = (quantities.get(bp.name) || 0) - bp.quantity;
          if (left > 0) quantities.set(bp.name, left);
          else quantities.delete(bp.name);
        }

        subtotal += Number(bundle.price);
        appliedOffers.push({ type: "bundle", name: bundle.name, price: Number(bundle.price) });
        hasPricedItems = true;
        if (bundle.deliveryIncluded) deliveryIncluded = true;
        else {
          hasChargeableItems = true;
          allPricedItemsInclusive = false;
        }
      }
    }
  }

  for (const [product, quantity] of quantities.entries()) {
    const numericQuantity = Math.max(1, Number(quantity || 1));
    const directBundle = (page.BUNDLE_OFFERS || []).find(bundle => bundle.name === product);
    const offerPrice = page.OFFERS?.[product]?.[numericQuantity];

    if (offerPrice != null) {
      subtotal += Number(offerPrice);
      appliedOffers.push({ type: "product_offer", product, quantity: numericQuantity, price: Number(offerPrice) });
      hasPricedItems = true;
      if (page.OFFER_DELIVERY_INCLUDED || directBundle?.deliveryIncluded) deliveryIncluded = true;
      else {
        hasChargeableItems = true;
        allPricedItemsInclusive = false;
      }
      continue;
    }

    if (page.PRICES?.[product] == null) continue;
    subtotal += Number(page.PRICES[product]) * numericQuantity;
    hasPricedItems = true;

    if (page.INCLUSIVE_PRODUCTS?.includes(product)) {
      // This product's own price includes delivery.
    } else {
      hasChargeableItems = true;
      allPricedItemsInclusive = false;
    }
  }

  let delivery = 0;
  if (deliveryMode === "included" || deliveryMode === "none") {
    delivery = 0;
  } else if (deliveryIncluded) {
    delivery = 0;
  } else if (hasPricedItems && hasChargeableItems) {
    delivery = Number(page.DELIVERY ?? 0);
  } else if (hasPricedItems && allPricedItemsInclusive) {
    delivery = 0;
  }

  const offer = appliedOffers.length === 0
    ? null
    : appliedOffers.length === 1
      ? appliedOffers[0]
      : { type: "combined", offers: appliedOffers };

  const items = [...quantities.entries()]
    .filter(([product, quantity]) => page.PRICES?.[product] != null && Number(quantity) > 0)
    .map(([product, quantity]) => ({
      product,
      quantity: Number(quantity),
      unitPrice: Number(page.PRICES[product]),
      lineTotal: Number((Number(page.PRICES[product]) * Number(quantity)).toFixed(2)),
      deliveryIncluded: (page.INCLUSIVE_PRODUCTS || []).includes(product)
    }));

  return {
    subtotal: Number(subtotal.toFixed(2)),
    delivery: Number(delivery.toFixed(2)),
    total: Number((subtotal + delivery).toFixed(2)),
    items,
    offer
  };
}

/**
 * تنسيق تفاصيل أصناف فاتورة ريفان. يستقبل:
 * [{ product: "جل غسيل ريفان 20 كيلو", quantity: 2 }, ...]
 * ويعيد سطوراً واضحة ليتم تمريرها إلى INVOICE_TEMPLATE.
 */
export function formatRivanInvoiceLines(lines = []) {
  const page = getPage("618622274665182");
  if (!page) return "";
  const totals = new Map();
  for (const line of Array.isArray(lines) ? lines : []) {
    const product = String(line?.product || "").trim();
    const quantity = Number(line?.quantity || 1);
    if (!product || !Number.isFinite(quantity) || quantity <= 0 || page.PRICES[product] == null) continue;
    totals.set(product, (totals.get(product) || 0) + quantity);
  }
  const normalizedLines = [...totals.entries()].map(([product, quantity]) => ({
    product,
    quantity
  }));
  const itemLines = normalizedLines.map(({ product, quantity }) => {
    const unitPrice = Number(page.PRICES[product]);
    const lineTotal = unitPrice * quantity;
    return `▪️ ${product} × ${quantity} × ${unitPrice} = ${lineTotal} دينار`;
  });
  const totalsResult = calculateOrderTotal("618622274665182", normalizedLines);
  if (totalsResult) {
    itemLines.push(`▪️ مجموع الأصناف: ${totalsResult.subtotal} دينار`);
    itemLines.push(`▪️ التوصيل مرة واحدة: ${totalsResult.delivery} دينار`);
  }
  return itemLines.join("\n");
}

