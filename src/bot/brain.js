// فحص نهائي يُستخدم من التطبيق الخارجي عند تشغيل السيرفر.
export function healthCheck() {
  const validation = validatePages();
  const pageIds = Object.keys(PAGES);
  return {
    ok: validation.ok && EXPERT_KNOWLEDGE_VALIDATION.ok && pageIds.length >= 1,
    version: BOT_VERSION,
    pageCount: pageIds.length,
    pages: pageIds.map(id => ({ id, name: PAGES[id].name })),
    validation,
    expertKnowledgeValidation: EXPERT_KNOWLEDGE_VALIDATION
  };
}


export function validateExpertKnowledge() {
  const errors = [];
  for (const id of Object.keys(PAGES)) {
    const profile = PAGE_EXPERT_KNOWLEDGE[id];
    if (!profile) {
      errors.push(`${id}: missing expert knowledge profile`);
      continue;
    }
    if (!profile.summary) errors.push(`${id}: missing expert summary`);
    if (!profile.products || Object.keys(profile.products).length === 0) {
      errors.push(`${id}: missing expert product knowledge`);
    }
    if (!Array.isArray(profile.faq) || profile.faq.length < 5) {
      errors.push(`${id}: expert FAQ coverage too low`);
    }
  }
  return { ok: errors.length === 0, errors };
}

export const EXPERT_KNOWLEDGE_VALIDATION = validateExpertKnowledge();

export const PAGE_VALIDATION = validatePages();
