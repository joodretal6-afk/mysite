function formatExpertKnowledge(profile) {
  if (!profile) return "";
  const productLines = Object.entries(profile.products || {})
    .map(([name, details]) => `- ${name}: ${details}`)
    .join("\n");
  const faqLines = (profile.faq || [])
    .map(([q, a]) => `س: ${q}\nج: ${a}`)
    .join("\n");
  return [
    "[ملخص المعرفة الخبيرة للصفحة]",
    profile.summary || "",
    "[تفاصيل المنتجات]",
    productLines,
    "[أسئلة وأجوبة جاهزة للفهم — لا تُنسخ حرفياً كل مرة، استخدم معناها بصياغة بشرية]",
    faqLines
  ].filter(Boolean).join("\n");
}

