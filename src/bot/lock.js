// 🔒 قفل لكل جلسة — يسلسل معالجة أحداث نفس العميل
//
// المشكلة: رسالتان متتاليتان من نفس العميل (أو إعادة إرسال فيسبوك)
// بتوصلوا كطلبَي POST متزامنين. كل واحد بيقرأ الذاكرة من KV، بيعدّل،
// وبيكتب — آخر كتابة بتفوز فبتضيع بيانات (رسالة فيها العنوان وتانية
// فيها الرقم، وحدة بتدعس التانية).
//
// الحل: mutex مبني على سلسلة وعود، مفتاحه sessionKey. أحداث نفس
// العميل بتنعالج بالتسلسل (الترتيب مضمون)، وأحداث عملاء مختلفين
// بتضل متوازية تماماً — ولا تأثير على بعض.
//
// 🔴 مهم: القفل لكل sessionKey لحاله. ما في قفل عام بيعطّل كل النظام،
// وما في حالة مشتركة بتنتقل بين العملاء.
// ═══════════════════════════════════════════════════════════

// ذيل السلسلة الحالي لكل مفتاح. لما تفضى السلسلة بننظّف المدخل حتى
// ما تكبر الخريطة بلا حد مع مرور الوقت.
const _tails = new Map();

export function withSessionLock(key, fn) {
  if (!key) return Promise.resolve().then(fn);   // بلا مفتاح = بلا تسلسل

  const prev = _tails.get(key) || Promise.resolve();

  // ننتظر اللي قبلنا (نتجاهل خطأه حتى ما تنكسر السلسلة)، وبعدها ننفّذ.
  const run = prev.then(() => fn(), () => fn());

  // الذيل الجديد بيكتمل حتى لو رمى fn — عشان اللي بعدنا ما يعلق.
  const tail = run.then(() => {}, () => {});
  _tails.set(key, tail);

  // تنظيف: لو ما إجا حدا بعدنا (إحنا لسا الذيل)، بنشيل المدخل.
  tail.then(() => { if (_tails.get(key) === tail) _tails.delete(key); });

  return run;
}

// للاختبار/التشخيص فقط
export function _activeLockCount() { return _tails.size; }
